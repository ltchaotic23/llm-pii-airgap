"""Transcript handling: harness tags, filtering, de-duplication and bad lines."""

from __future__ import annotations

import json
import unittest

from support import FAKE_SECRET, scrub_jsonl_stream, strip_harness_tags


def user(text_or_parts, **extra) -> str:
    return json.dumps({"type": "user", "message": {"content": text_or_parts}, **extra})


class TestRecordFiltering(unittest.TestCase):
    def test_only_human_prompts_are_kept(self) -> None:
        skipped = [
            json.dumps({"type": "assistant", "message": {"content": "model reply"}}),
            user("side chain", isSidechain=True),
            user("sub-agent", agentId="a1"),
            user("meta", isMeta=True),
            user("summary", isCompactSummary=True),
            user("hidden", isVisibleInTranscriptOnly=True),
            user("tool", toolUseResult={"stdout": "x"}),
            user([{"type": "tool_result", "content": "x"}]),
            user("<local-command-stdout>x</local-command-stdout>"),
            user("<scheduled-task>x</scheduled-task>"),
            user("<side-sessions-event>x</side-sessions-event>"),
            user("<ci-monitor-event>x</ci-monitor-event>"),
            user("[Workflow harness] x"),
            user("[handback] x"),
            user("Caveat: generated by harness"),
            user("[Request interrupted by user]"),
            user([{"type": "text", "text": "<system-reminder>ctx</system-reminder>"},
                  {"type": "text", "text": "<command-name>/clear</command-name>"}]),
            user([{"type": "text", "text": "<system-reminder>ctx</system-reminder>"},
                  {"type": "text", "text": "[Request interrupted by user]"}]),
            user("   "),
            json.dumps(["not", "an", "object"]),
            json.dumps("just a string"),
            json.dumps({"type": "user", "message": {"content": 42}}),
        ]
        rows, summary = scrub_jsonl_stream([*skipped, user("keep me")])
        self.assertEqual([row["text"] for row in rows], ["keep me"])
        self.assertEqual(summary["non_user_skipped"], len(skipped))

    def test_content_without_a_message_wrapper(self) -> None:
        rows, _ = scrub_jsonl_stream([json.dumps({"type": "user", "content": "plain"})])
        self.assertEqual(rows[0]["text"], "plain")

    def test_text_parts_are_joined_and_image_parts_ignored(self) -> None:
        parts = [
            {"type": "text", "text": "first"},
            {"type": "image", "source": {"type": "base64", "data": "iVBORw0KGgo" + "AAAA1111" * 20}},
            {"type": "text", "text": "second"},
        ]
        rows, summary = scrub_jsonl_stream([user(parts)])
        self.assertEqual(rows[0]["text"], "first\nsecond")
        self.assertEqual(summary["redactions"], {})

    def test_records_without_uuid_are_never_deduplicated(self) -> None:
        rows, summary = scrub_jsonl_stream([user("same"), user("same")])
        self.assertEqual((len(rows), summary["duplicates_skipped"]), (2, 0))

    def test_uuid_and_timestamp_are_copied_as_they_are(self) -> None:
        rows, _ = scrub_jsonl_stream([user("hi", uuid=7, timestamp="2026-01-01T00:00:00Z")])
        self.assertEqual(rows[0], {"uuid": 7, "timestamp": "2026-01-01T00:00:00Z", "text": "hi"})


class TestBadInput(unittest.TestCase):
    """A malformed record is counted and skipped; it never stops the rest of the file."""

    def test_blank_lines_are_not_counted(self) -> None:
        rows, summary = scrub_jsonl_stream(["", "   ", user("one"), "\n"])
        self.assertEqual((len(rows), summary["lines_read"], summary["invalid_json"]), (1, 1, 0))

    def test_bad_line_in_the_middle(self) -> None:
        rows, summary = scrub_jsonl_stream([user("one", uuid="1"), "{not json", user("two", uuid="2")])
        self.assertEqual([row["text"] for row in rows], ["one", "two"])
        self.assertEqual((summary["invalid_json"], summary["lines_read"]), (1, 3))

    def test_non_string_text_part(self) -> None:
        parts = [{"type": "text", "text": 5}, {"type": "text", "text": None}, {"type": "text", "text": "kept"}]
        rows, _ = scrub_jsonl_stream([user(parts, uuid="1"), user("next", uuid="2")])
        self.assertEqual([row["text"] for row in rows], ["kept", "next"])

    def test_deeply_nested_line(self) -> None:
        deep = "[" * 100_000 + "]" * 100_000
        rows, summary = scrub_jsonl_stream([deep, user(f"DB_PASSWORD={FAKE_SECRET}")])
        self.assertEqual(summary["invalid_json"], 1)
        self.assertEqual([row["text"] for row in rows], ["DB_PASSWORD=<SECRET>"])

    def test_oversized_integer_line_counts_as_invalid_json(self) -> None:
        big_int = '{"id": ' + "1" * 4500 + "}"
        rows, summary = scrub_jsonl_stream([big_int, user("keep me")])
        self.assertEqual(summary["invalid_json"], 1)
        self.assertEqual([row["text"] for row in rows], ["keep me"])


class TestHarnessTags(unittest.TestCase):
    def test_every_block_type_is_removed(self) -> None:
        for tag in ("system-reminder", "side-sessions-event", "scheduled-task", "task-notification",
                    "ci-monitor-event", "local-command", "pasted_content", "pasted_content_2",
                    "ide_selection", "ide_opened_file", "attachment"):
            with self.subTest(tag=tag):
                text = f"before <{tag} id=\"1\">secret\nmultiline</{tag}> after"
                self.assertEqual(strip_harness_tags(text), "before  after")

    def test_inline_markers_are_removed(self) -> None:
        self.assertEqual(
            strip_harness_tags("a [Image #2] b [Image #3: source: shot.png] c [Pasted text #1 +20 lines] d"),
            "a  b  c  d",
        )

    def test_similar_tags_are_left_alone(self) -> None:
        for text in ("<system-reminders>x</system-reminders>", "<attachments>x</attachments>", "<b>x</b>"):
            with self.subTest(text=text):
                self.assertEqual(strip_harness_tags(text), text)

    def test_two_blocks_and_the_text_between_them(self) -> None:
        text = "a <system-reminder>x</system-reminder> b <attachment>y</attachment> c"
        self.assertEqual(strip_harness_tags(text), "a  b  c")

    def test_closing_tag_must_match_the_opening_tag(self) -> None:
        text = "<system-reminder>x</attachment> keep <system-reminder>y</system-reminder>"
        self.assertEqual(strip_harness_tags(text), "")

    def test_unclosed_outer_tag_with_malformed_closer_does_not_disable_inner_stripping(self) -> None:
        text = "<attachment> <system-reminder>INTERNAL_FAKE</system-reminder> user text </attachment"
        self.assertEqual(strip_harness_tags(text), "<attachment>  user text </attachment")

    def test_self_closing_tag_and_markdown_image_links_are_preserved(self) -> None:
        self.assertEqual(
            strip_harness_tags('<attachment id="1"/> Important user prompt! <attachment id="2">drop</attachment>'),
            "Important user prompt!",
        )
        markdown = "[Image of architecture diagram](docs/arch.png) and ![Image comparison](before-after.png)"
        self.assertEqual(strip_harness_tags(markdown), markdown)



class TestStream(unittest.TestCase):
    def test_strip_harness_tags(self) -> None:
        raw = (
            "Hello world\n"
            "<system-reminder>Internal prompt</system-reminder>\n"
            "<pasted_content_1>Secret dump</pasted_content_1>\n"
            "[Image #1] Keep this sentence."
        )
        cleaned = strip_harness_tags(raw)
        self.assertNotIn("Internal prompt", cleaned)
        self.assertNotIn("Secret dump", cleaned)
        self.assertNotIn("[Image #1]", cleaned)
        self.assertIn("Hello world", cleaned)
        self.assertIn("Keep this sentence.", cleaned)

    def test_scrub_jsonl_stream_filtering_and_dedup(self) -> None:
        fake_key = "ghp_" + ("Z9y8X7w6V5" * 4)
        records = [
            {"type": "assistant", "uuid": "u0", "message": {"content": "Model reply"}},
            {"type": "user", "uuid": "u1", "isSidechain": True, "message": {"content": "Skip me"}},
            {
                "type": "user",
                "uuid": "u2",
                "message": {"content": [{"type": "tool_result", "content": "output"}]},
            },
            {
                "type": "user",
                "uuid": "u3",
                "timestamp": "2026-11-15T12:00:00Z",
                "message": {"content": f"<system-reminder>ctx</system-reminder>Use {fake_key} on 10.0.0.5"},
            },
            # Duplicate uuid u3 should be dropped
            {
                "type": "user",
                "uuid": "u3",
                "timestamp": "2026-11-15T12:00:00Z",
                "message": {"content": "Duplicate"},
            },
            {"type": "user", "uuid": "u4", "message": {"content": "<task-notification>Ignore</task-notification>"}},
        ]
        lines = [json.dumps(r) for r in records] + ["{bad json"]
        rows, summary = scrub_jsonl_stream(lines)
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0]["uuid"], "u3")
        self.assertEqual(rows[0]["text"], "Use <API_KEY> on <IP>")
        self.assertEqual(summary["duplicates_skipped"], 1)
        self.assertEqual(summary["invalid_json"], 1)
        self.assertEqual(summary["rows_kept"], 1)
        self.assertEqual(summary["redactions"]["<API_KEY>"], 1)
        self.assertEqual(summary["redactions"]["<IP>"], 1)


